import { parseAll, postSchema, type Post } from './types';

/**
 * The blog ("פוסטים אחרונים") and news ("חדשות קיסר") archives, as listed on
 * the client's homepage.
 *
 * WHAT WE ACTUALLY HAVE. The homepage lists each post's title, its thumbnail and
 * its permalink. It does not print publication dates, and it does not print
 * teasers. Only the homepage could be read, so that is the whole of it. Every
 * record here is therefore `needsReview: true`, and two fields are conventions
 * rather than data:
 *
 *   `publishedAt` is `PENDING_DATE`, a deliberately impossible sentinel. It is
 *   not a guess dressed up as a date. Nothing may present it to a reader:
 *   use `hasRealDate()` before rendering one, and sort the archive by array
 *   order (the client's own newest-first ordering) until the real dates arrive.
 *
 *   `excerpt` repeats the title wherever no teaser exists. `hasRealExcerpt()`
 *   says whether a record has a distinct one; none does yet. Writing invented
 *   teasers for a hundred posts we have not read would put words in the
 *   client's mouth a hundred times over.
 *
 * TITLES ARE TRIMMED, NOT REWRITTEN. Legacy titles piled several keyword
 * phrases into one string separated by pipes — "ניהול נכסים בירושלים | ניהול
 * נכסים ללא תשלום | אחזקת מבנים בירושלים | חברה לניהול נכסים בירושלים | …".
 * `title` keeps the first phrase, which is the client's own wording, and drops
 * the pile. Nothing is added.
 *
 * A NOTE FOR THE CONTENT REVIEW. The archive contains long runs of near-identical
 * city posts (five separate "ניהול נכסים בתל אביב" posts, two for בת ים, two for
 * ראשון לציון, three on ניהול מרכזים מסחריים). The slugs below disambiguate them
 * with a numeric suffix so every legacy URL still resolves, but these are
 * doorway pages and the right long-term fix is to consolidate each cluster into
 * one real page and point the rest at it. That is a decision for the client.
 *
 * Four posts appear in both the blog carousel and the news carousel; they are
 * recorded once, as news, since that is the more specific category.
 *
 * `/רוצה-לדעת-כמה-הדירה-שלך-שווה/` also appears in the news carousel but is the
 * valuation service page; it is handled in `services.ts`, not here.
 */

