/** True once the client's real publication date has replaced the sentinel. */
export function hasRealDate(post: Post): boolean {
  return post.publishedAt !== PENDING_DATE;
}

/** True once a real teaser has replaced the title-as-excerpt convention. */
export function hasRealExcerpt(post: Post): boolean {
  return post.excerpt !== post.title;
}

export const blogPosts: Post[] = posts.filter((post) => post.kind === 'blog');
export const newsPosts: Post[] = posts.filter((post) => post.kind === 'news');

export function postPath(post: Pick<Post, 'kind' | 'slug'>): string {
  return `/${post.kind}/${post.slug}`;
}

export function getPost(kind: Post['kind'], slug: string): Post | undefined {
  return posts.find((post) => post.kind === kind && post.slug === slug);
}
